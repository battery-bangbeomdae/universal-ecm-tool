function mapping = inferMapping(names)
%INFERMAPPING Match quantity names across explicit units and common languages.
arguments
 names
end
names=string(names);
aliases=struct( ...
 'frequency',{{'frequencyhz','freqhz','frequency','freq','f','주파수'}}, ...
 'real',{{'zrealohm','zresource','realohm','reohm','rezohm','rrealohm','impedancerohm','zprime','zreal','real','rez','re','zr','rreal','실수부','임피던스실수부'}}, ...
 'imag',{{'zimagohm','zimsource','imagohm','imohm','negimzohm','imzohm','rimgohm','impedanceiohm','zimagraw ohm','zimag','zim','imz','imag','im','zi','zdoubleprime','negimz','negimag','rimg','zimagraw','허수부','임피던스허수부','음의허수부'}}, ...
 'magnitude',{{'magnitudeohm','abszohm','zampmohm','magnitude','absz','zamp','zmod','modz','zmag','impedancemagnitude','임피던스크기'}}, ...
 'phase',{{'phasedeg','phasezdeg','zphdeg','phaserad','phase','phasez','zph','zphase','argz','anglez','theta','위상'}}, ...
 'time',{{'times','time','elapsedtimes','timems','timestamps','elapsedtime','testtime','timestamp','t','시간','경과시간'}}, ...
 'current',{{'currenta','currentma','current','ia','i','전류'}}, ...
 'voltage',{{'voltagev','voltagemv','voltage','uv','v','u','ecell','cellvoltage','전압','단자전압'}}, ...
 'source',{{'sourceid','datasetid','출처id'}},'cell',{{'cellid','batteryid','cellname','셀id'}}, ...
 'test',{{'testid','recordid','measurementid','시험id'}},'spectrum',{{'spectrumid','segmentid','sweepid','eisid','스펙트럼id'}}, ...
 'soc',{{'socpct','socpercent','soc','stateofcharge','rwthsocpct','rwthsoc','충전상태'}}, ...
 'temperature',{{'temperaturec','temperaturedegc','temperaturestartc','eistempc','rwthtemperaturedegc','temperature','temp','temperaturestart','eistemp','rwthtemperature','온도','측정온도'}}, ...
 'soh',{{'sohpct','sohpercent','soh','rwthsohfraction','rwthsoh','stateofhealth','건강상태'}}, ...
 'calendar',{{'calendar','calendarage','calendardays','calendaragedays','aging','ageing','agingtime','ageingtime','agingdays','ageingdays','storage','storageage','storagedays','elapsedagingdays','열화경과일'}}, ...
 'cycle',{{'cyclenumber','cycleindex','cyclecount','rwthncycle','cycle','사이클','사이클수'}}, ...
 'status',{{'statuscode','status','상태'}});   % [J] instrument C/D/R status (readRaw writes status_code)
fields=fieldnames(aliases);mapping=struct();
for k=1:numel(fields)
 f=fields{k};wanted=normalize(string(aliases.(f)));hit=false(size(names));
 for j=1:numel(names)
  info=uecm.columnInfo(names(j),string(f));
  hit(j)=ismember(normalize(info.Base),wanted)||ismember(normalize(names(j)),wanted);
 end
 % A package contains both experiment test_id and per-measurement measurement_id.
 % Prefer the explicit experiment key; measurement_id remains a legacy alias.
 if strcmp(f,'test')
  canonical=find(names=="test_id");
  if numel(canonical)==1,mapping.(f)=names(canonical);continue,end
 end
 indices=find(hit);
 if numel(indices)==1,mapping.(f)=names(indices);else,mapping.(f)="";end
end
end
function value=normalize(value)
value=lower(string(value));
value=replace(value,["z''","z″","z’'","z'","z′","|z|"],["zdoubleprime","zdoubleprime","zdoubleprime","zprime","zprime","absz"]);
value=regexprep(value,'[^a-z0-9가-힣]','');
end
